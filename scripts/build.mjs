#!/usr/bin/env node
// Builds everything apps copy from tokens/tokens.json and marks/marks.mjs. No dependencies.
//
//   dist/tokens.resolved.json   every value, light shades included
//   dist/tokens.css             CSS custom properties (dark by default, light by media query or data-theme)
//   dist/Design.swift           SwiftUI colours for iOS and macOS
//   marks/out/<product>/        icon-dark.svg, icon-light.svg, mark-dark.svg, mark-light.svg
//   dist/preview.html           every mark and colour on one page
//   docs/img/*.svg              the figures in the README and the guide
//
// Run: node scripts/build.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { MARKS, mix } from "../marks/marks.mjs";
import { figures } from "./figures.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const T = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));
const M = T.marks;
const LIGHT_GROUND = T.grounds.light.ground;

// --- Colour maths: WCAG contrast, and darkening in HSL so a shade keeps its hue.
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const hex = (c) => `#${c.map((x) => Math.round(Math.max(0, Math.min(1, x)) * 255).toString(16).padStart(2, "0")).join("").toUpperCase()}`;
const lum = (h) => {
  const c = rgb(h).map((x) => (x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
export const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
/** `h` darkened (hue and saturation kept) until it reaches `target`:1 on `bg`. */
export function shade(h, bg, target) {
  const [r, g, b] = rgb(h);
  const mx = Math.max(r, g, b);
  const mn = Math.min(r, g, b);
  const d = mx - mn;
  let l = (mx + mn) / 2;
  let s = 0;
  let hu = 0;
  if (d) {
    s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn);
    hu = (mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4) / 6;
  }
  const f = (p, q, x) => {
    const t = (x + 1) % 1;
    return t < 1 / 6 ? p + (q - p) * 6 * t : t < 1 / 2 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p;
  };
  for (; l > 0; l -= 0.005) {
    const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
    const p = 2 * l - q;
    const c = hex([f(p, q, hu + 1 / 3), f(p, q, hu), f(p, q, hu - 1 / 3)]);
    if (contrast(c, bg) >= target) return c;
  }
  return h;
}

// --- Resolve each product's accent into the shades the rules call for.
const products = {};
for (const [key, p] of Object.entries(T.products)) {
  const out = { ...p };
  if (p.accent) {
    const tileBg = mix(p.accent, M.lightTileBase, M.lightTileTint);
    out.shades = {
      dark: p.accent,
      lightGraphic: shade(p.accent, LIGHT_GROUND, M.contrast.graphic),
      lightText: shade(p.accent, LIGHT_GROUND, M.contrast.text),
      lightTile: tileBg,
      lightTileLit: shade(p.accent, tileBg, M.contrast.graphic),
    };
    out.contrastOnDark = Number(contrast(p.accent, T.grounds.dark.ground).toFixed(1));
  }
  products[key] = out;
}
const resolved = { ...T, products };
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist/tokens.resolved.json"), `${JSON.stringify(resolved, null, 2)}\n`);

// --- CSS
const v = (name, value) => `  --ds-${name}: ${value};`;
const scheme = (mode) => {
  const lines = [];
  for (const [k, val] of Object.entries(T.grounds[mode])) lines.push(v(k, val));
  for (const [k, val] of Object.entries(T.text[mode])) lines.push(v(`text-${k}`, val));
  lines.push(v("lit", T.lit[mode].fill), v("on-lit", T.lit[mode].on));
  for (const [k, val] of Object.entries(T.states)) if (!k.startsWith("$")) lines.push(v(k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`), val[mode]));
  lines.push(v("lab-ask", T.lab.ask[mode]));
  for (const [k, p] of Object.entries(products)) {
    if (!p.shades) continue;
    lines.push(v(`${k}`, mode === "dark" ? p.shades.dark : p.shades.lightGraphic));
    lines.push(v(`${k}-tint`, mode === "dark" ? p.shades.dark : p.shades.lightText));
  }
  return lines.join("\n");
};
const css = `/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit; copy into an app. */
/* Dark by default. Light follows the system, or set data-theme="light" | "dark" on <html>. */
/* An app picks its accent once:  :root { --ds-accent: var(--ds-lyrate); --ds-tint: var(--ds-lyrate-tint); } */
:root {
  color-scheme: dark;
${scheme("dark")}
${v("night", M.night)}
${v("night-high", M.nightHigh)}
${v("paper", M.paper)}
${v("navy", M.navy)}
${v("wordmark-font", `"${T.type.wordmark.family}", -apple-system, system-ui, sans-serif`)}
${v("wordmark-weight", T.type.wordmark.weight)}
${v("wordmark-tracking", T.type.wordmark.tracking)}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${scheme("light").replace(/^ {2}/gm, "    ")}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${scheme("light")}
}
`;
writeFileSync(join(root, "dist/tokens.css"), css);

// --- Swift
const sx = (h) => `0x${h.slice(1)}`;
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
// Swift keywords a product key might collide with.
const SWIFT_RESERVED = new Set(["throw", "case", "default", "do", "in", "is", "let", "var", "func", "class", "struct", "enum", "return", "repeat", "switch", "where", "while", "for", "if", "else", "guard", "try", "catch", "import", "init", "self", "super", "static", "public", "private", "internal", "operator", "protocol", "extension", "subscript", "typealias", "defer", "break", "continue", "fallthrough", "rethrows", "throws", "as", "any", "nil", "true", "false"]);
const swiftName = (k) => (SWIFT_RESERVED.has(k) ? `\`${k}\`` : k);
const pair = (light, dark) => `Color.design(light: ${sx(light)}, dark: ${sx(dark)})`;
const swiftAccents = Object.entries(products)
  .filter(([, p]) => p.shades)
  .map(
    ([k, p]) => `        /// ${p.name}: marks and graphics (3:1 on light ground).
        public static let ${swiftName(k)} = ${pair(p.shades.lightGraphic, p.shades.dark)}
        /// ${p.name}: the tint, for tab selection, toggles, progress and links (4.5:1 on light ground).
        public static let ${k}Tint = ${pair(p.shades.lightText, p.shades.dark)}`,
  )
  .join("\n");
const swift = `// Generated by scripts/build.mjs from tokens/tokens.json. Do not edit; copy into an app.
import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

public enum Design {
    /// Grounds: ours, in both appearances (sheets and grouped lists too).
    public enum Ground {
${Object.keys(T.grounds.dark).map((k) => `        public static let ${k} = ${pair(T.grounds.light[k], T.grounds.dark[k])}`).join("\n")}
    }

    /// Text and icons: the system's label colours (P2). Never cream.
    public enum Text {
        public static let primary = Color.primary
        public static let secondary = Color.secondary
        public static let tertiary = Color.systemTertiaryLabel
    }

    /// Lit: the fill of the selected or lit thing and of the primary button.
    public enum Lit {
        public static let fill = ${pair(T.lit.light.fill, T.lit.dark.fill)}
        public static let on = ${pair(T.lit.light.on, T.lit.dark.on)}
    }

    /// Shared states. Never an accent.
    public enum State {
${Object.entries(T.states).filter(([k]) => !k.startsWith("$")).map(([k, val]) => `        public static let ${camel(k)} = ${pair(val.light, val.dark)}`).join("\n")}
    }

    /// Lab tools only: something is waiting on your answer.
    public static let labAsk = ${pair(T.lab.ask.light, T.lab.ask.dark)}

    /// Fixed mark colours.
    public enum Mark {
        public static let night = Color(hex: ${sx(M.night)})
        public static let paper = Color(hex: ${sx(M.paper)})
        public static let navy = Color(hex: ${sx(M.navy)})
    }

    /// Each product's accent. An app sets its tint once: .tint(Design.Accent.lyrateTint)
    public enum Accent {
${swiftAccents}
    }
}

extension Color {
    init(hex: UInt32) {
        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)
    }

    static func design(light: UInt32, dark: UInt32) -> Color {
        #if canImport(UIKit)
        Color(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(Color(hex: dark)) : UIColor(Color(hex: light)) })
        #elseif canImport(AppKit)
        Color(nsColor: NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? NSColor(Color(hex: dark)) : NSColor(Color(hex: light)) })
        #endif
    }

    static var systemTertiaryLabel: Color {
        #if canImport(UIKit)
        Color(uiColor: .tertiaryLabel)
        #elseif canImport(AppKit)
        Color(nsColor: .tertiaryLabelColor)
        #endif
    }
}
`;
writeFileSync(join(root, "dist/Design.swift"), swift);

// --- Marks
const png = (f) => `data:image/png;base64,${readFileSync(join(root, "marks/avia", f)).toString("base64")}`;
const aviaPng = { litPng: png("tent-lit.png"), shadePng: png("tent-shade.png") };
const ctx = (key, mode, tiled) => {
  const p = products[key];
  const dark = mode === "dark";
  const ground = !tiled ? "none" : dark ? "night" : p.shades?.lightTile ?? M.lightTileBase;
  const lightLitBg = tiled ? ground : LIGHT_GROUND;
  const lit = !p.shades ? (dark ? M.paper : M.navy) : dark ? p.shades.dark : shade(p.accent, lightLitBg, M.contrast.graphic);
  const avia = key === "avia" ? { ...aviaPng, lit: dark ? p.accent : p.lightArt.lit, shade: dark ? p.accentShade : p.lightArt.shade } : undefined;
  return { lit, ink: dark ? M.paper : M.navy, dark, ground, t: M, avia };
};
const rendered = {};
for (const key of Object.keys(MARKS)) {
  const dir = join(root, "marks/out", key);
  mkdirSync(dir, { recursive: true });
  rendered[key] = {};
  for (const [file, mode, tiled] of [["icon-dark", "dark", true], ["icon-light", "light", true], ["mark-dark", "dark", false], ["mark-light", "light", false]]) {
    const svg = MARKS[key](ctx(key, mode, tiled));
    rendered[key][file] = svg;
    writeFileSync(join(dir, `${file}.svg`), `${svg}\n`);
  }
}

